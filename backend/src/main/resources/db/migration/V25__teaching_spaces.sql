CREATE TABLE teaching_space (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 personal_owner_id BIGINT UNIQUE REFERENCES auth_users(id),
 name VARCHAR(150) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE space_teacher (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 space_id BIGINT NOT NULL REFERENCES teaching_space(id), user_id BIGINT NOT NULL REFERENCES auth_users(id),
 is_owner BOOLEAN NOT NULL DEFAULT FALSE, manage_student_access BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(space_id,user_id)
);
CREATE TABLE space_student (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 space_id BIGINT NOT NULL REFERENCES teaching_space(id), user_id BIGINT NOT NULL REFERENCES auth_users(id),
 name VARCHAR(100) NOT NULL, archived_at TIMESTAMP WITH TIME ZONE,
 credential_version BIGINT NOT NULL DEFAULT 0, UNIQUE(space_id,user_id)
);
CREATE TABLE student_credential (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES space_student(id), code VARCHAR(8) NOT NULL UNIQUE,
 primary_code BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX uq_student_primary_code ON student_credential(student_id) WHERE primary_code;
CREATE TABLE space_invitation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 space_id BIGINT NOT NULL REFERENCES teaching_space(id), token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, used_at TIMESTAMP WITH TIME ZONE, revoked_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE class_teacher (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 classroom_id BIGINT NOT NULL REFERENCES classroom(id), user_id BIGINT NOT NULL REFERENCES auth_users(id),
 UNIQUE(classroom_id,user_id)
);
ALTER TABLE classroom ADD COLUMN space_id BIGINT REFERENCES teaching_space(id);
ALTER TABLE classroom_member ADD COLUMN student_id BIGINT REFERENCES space_student(id);
ALTER TABLE worksheet_assignment ADD COLUMN space_id BIGINT REFERENCES teaching_space(id);

INSERT INTO teaching_space(personal_owner_id,name,created_at)
 SELECT id, name || '''s teaching space', created_at FROM auth_users
 WHERE role='TEACHER' OR id IN (SELECT teacher_id FROM classroom)
 OR id IN (SELECT w.user_id FROM worksheet_assignment a JOIN worksheet_revision r ON r.id=a.worksheet_revision_id JOIN worksheet w ON w.id=r.worksheet_id);
INSERT INTO space_teacher(space_id,user_id,is_owner,manage_student_access)
 SELECT id,personal_owner_id,TRUE,TRUE FROM teaching_space;
UPDATE classroom c SET space_id=s.id FROM teaching_space s WHERE s.personal_owner_id=c.teacher_id;
INSERT INTO class_teacher(classroom_id,user_id) SELECT id,teacher_id FROM classroom;
UPDATE worksheet_assignment a SET space_id=c.space_id FROM classroom c WHERE c.id=a.classroom_id;
UPDATE worksheet_assignment a SET space_id=s.id
 FROM worksheet_revision r, worksheet w, teaching_space s
 WHERE a.classroom_id IS NULL AND r.id=a.worksheet_revision_id AND w.id=r.worksheet_id AND s.personal_owner_id=w.user_id;
INSERT INTO space_student(space_id,user_id,name)
 SELECT p.space_id,p.user_id,u.name FROM (
 SELECT c.space_id,m.user_id FROM classroom_member m JOIN classroom c ON c.id=m.classroom_id
 UNION SELECT space_id,user_id FROM worksheet_assignment
 ) p JOIN auth_users u ON u.id=p.user_id;
UPDATE classroom_member m SET student_id=s.id FROM classroom c,space_student s
 WHERE c.id=m.classroom_id AND s.space_id=c.space_id AND s.user_id=m.user_id;
INSERT INTO student_credential(student_id,code,primary_code)
 SELECT student_id,student_code,ROW_NUMBER() OVER(PARTITION BY student_id ORDER BY joined_at,id)=1
 FROM classroom_member m WHERE student_code IS NOT NULL AND left_at IS NULL
 AND EXISTS(SELECT 1 FROM classroom c WHERE c.id=m.classroom_id AND c.archived_at IS NULL);
