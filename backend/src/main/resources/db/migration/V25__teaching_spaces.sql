CREATE TABLE assignment_delivery (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id UUID NOT NULL UNIQUE, space_id BIGINT NOT NULL REFERENCES teaching_space(id),
 creator_id BIGINT NOT NULL REFERENCES auth_users(id), classroom_id BIGINT REFERENCES classroom(id),
 revision_id BIGINT NOT NULL REFERENCES worksheet_revision(id), title VARCHAR(150),
 assigned_at TIMESTAMP WITH TIME ZONE NOT NULL, closed_at TIMESTAMP WITH TIME ZONE
);
INSERT INTO assignment_delivery(batch_id,space_id,creator_id,classroom_id,revision_id,assigned_at,closed_at)
 SELECT a.batch_id,MIN(a.space_id),MIN(w.user_id),MIN(a.classroom_id),MIN(r.id),MIN(a.assigned_at),
 CASE WHEN BOOL_AND(a.removed_at IS NOT NULL) THEN MAX(a.removed_at) ELSE NULL END
 FROM worksheet_assignment a JOIN worksheet_revision r ON r.id=a.worksheet_revision_id JOIN worksheet w ON w.id=r.worksheet_id GROUP BY a.batch_id;
